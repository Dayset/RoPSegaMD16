; input-replay: deterministic input replay overlay (issue #240).
;
; Hooks joypad_queue_pop ($1350) — the single choke point every pad
; consumer reads through — and feeds pad bytes from a script table
; appended to the ROM, so the same ROM + the same script = the same
; run, every time. No xdotool, no save state, no live input.
;
; WHY THIS HOOK (not pad_latch_11bb8, the issue's default design):
; pad_latch_11bb8 ($11BB8) is DEAD CODE in the shipped ROM —
; disasm/ghidra/not_reachable_from_entry.txt: "0x11BB8 called-by-
; direct: none". Nothing calls it, so a hook there would feed
; nothing. The LIVE path is: VBlank handler ($1272) reads pad 1
; from the hardware into $FF0018 on change -> the VBlank tail
; pushes it into a 16-byte ring at $FF001C (write idx $FF001A,
; read idx $FF001B, last value $FF002C) -> every consumer reads
; through joypad_queue_pop ($1350), which pops the ring (or
; returns the last value when empty, so a held button keeps
; reading as pressed) and stores the byte in $FF0E14 (pad 1) /
; $FF8646 (pad 2). Hooking the pop covers the main loop, the
; menus, and sys_wait_button_press alike.
;
; Pad byte format (after the not.b in pad1_read): bit=1 means
; pressed. bit 0 Up, 1 Down, 2 Left, 3 Right, 4 B, 5 C, 6 A,
; 7 Start. ($FF0018==$40 is A alone.)
;
; HOOK SITE ($1350, 8 bytes, prologue of joypad_queue_pop):
;   $1350 moveq #0,d0        (2 B)
;   $1352 moveq #0,d1        (2 B)
;   $1354 move.w #$2700,sr   (4 B)
; Replaced by: jsr replay_pop.l (6 B) + nop (2 B).
; The pop body starts at $1358 (move.b $FF001B,d1).
;
; STACK DISCIPLINE — THE D-CRASH RULE (see big-rework-full
; .scratch-big-rework-full/d-crash/REPORT.md §6): a jsr hook that
; jmps into a routine WITHOUT discarding the hook jsr's return
; makes the routine's rts return to the hook site and re-run the
; body with a corrupted frame. The C blob's skip_hero/skip_promote
; did exactly this and collapsed the stack to PC=0. So BOTH paths
; below discard the hook return with addq.w #4,sp FIRST:
;   - replay path: compute the pad, addq.w #4,sp, rts (returns to
;     the caller of joypad_queue_pop with d0 = scripted byte).
;   - passthrough: re-execute the displaced prologue, addq.w #4,sp,
;     jmp $1358 (the pop body runs ONCE; its rts returns to the
;     caller). Without the discard the body would run TWICE and pop
;     two queue entries per call.
; The original pop clobbers d0/d1/a0 and SR; the hook clobbers no
; more than that (d1/a0 are saved/restored around the table walk).
;
; TABLE: entries of 4 bytes — dc.w frame_count, dc.b pad1, dc.b 0
; (pad2 reserved) — sorted by frame_count ascending, terminated by
; dc.w $FFFF. The pad in force at frame F is the last entry with
; frame_count <= F; before the first entry the pad is $00 (nothing
; pressed). Frame = low word of the frame counter at $FF0012
; (counter at $FF0010, long, +1 every VBlank). Runs are < 65536
; frames, so the word never wraps. The table is generated by
; build.py from a route file and appended here via incbin.
;
; MAGIC: REPLAY_MAGIC is $9C07 in this build (the "magic word is
; set"). A build without the overlay has no hook at all, so replay
; is off unless selected (make check gate).
;
; Blob base $FE000: free 0xFF padding in the original, flat-zoomed,
; and walk-unused-frames ROMs (highest non-FF past $FD000 is
; $FDAC3 in walk-unused-frames; $FE000..EOF is all 0xFF in all
; three). One fixed base for the overlay on any base ROM.

        org $FE000

REPLAY_MAGIC:
        dc.w $9C07

replay_pop:
        cmpi.w #$9C07,REPLAY_MAGIC
        bne .passthrough
        ; --- replay active: walk the table, return the pad in d0 ---
        movem.l d1/a0,-(sp)
        move.w $FF0012,d0               ; frame counter, low word
        lea TABLE,a0
        moveq #0,d1                     ; current pad = 0 (default)
.scan:
        cmpi.w #$FFFF,(a0)              ; terminator?
        beq .done
        cmp.w (a0),d0                   ; entry frame <= current frame?
        blo .done                       ; entry frame > frame: stop
        move.b 2(a0),d1                 ; pad = entry pad
        addq.l #4,a0
        bra .scan
.done:
        moveq #0,d0
        move.b d1,d0                    ; d0 = scripted pad, zero-extended
        movem.l (sp)+,d1/a0
        addq.w #4,sp                    ; discard the hook jsr return
        rts                             ; -> caller of joypad_queue_pop
.passthrough:
        ; --- replay off: run the displaced prologue, then the body ---
        moveq #0,d0
        moveq #0,d1
        move.w #$2700,sr
        addq.w #4,sp                    ; discard the hook jsr return
        jmp $1358                       ; pop body (runs once)

TABLE:
        incbin "replay_table.bin"
