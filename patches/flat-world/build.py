#!/usr/bin/env python3
"""Build the flat-world ROM: $E358 dispatch-hook flat plane for the OVERWORLD.

Reads the original ROM, writes the flatworld blob at $FD0CC, patches the
2 $E358 dispatch sites + the 3 map_chunk_pos call sites, fixes both
checksums, and emits the .ips (round-trip verified) + changed-bytes.txt.

Stub addresses are parsed from the vasm listing (flatworld.lst) — never
hardcoded. The original ROM is never modified (read-only here).
The blob is assembled here from source.s (== flatworld.s, generated by
gen_flatworld.py from disasm/src/rop.s); the original build read a
pre-built flatworld.bin from its scratch dir.
"""
import hashlib, struct, re, subprocess, sys, os

DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(DIR))
CHECKSUM = os.environ.get('ROP_CHECKSUM', os.path.join(REPO, 'tools', 'checksum.py'))
VASM = os.environ.get('ROP_VASM', os.path.join(REPO, 'tools', 'vasm', 'vasmm68k_mot'))
SCRATCH = os.path.join(REPO, 'build', 'scratch-flat-world')
ORIG = os.environ.get('ROP_ORIGINAL', os.path.join(REPO, 'rop-original.gen'))
OUT = os.environ.get('ROP_OUT', os.path.join(REPO, 'build', 'rop-flat-world.rom'))
PATCHDIR = DIR
BLOB_BASE = 0xFD0CC

# --- assemble source.s (== flatworld.s, generated by gen_flatworld.py) ---
os.makedirs(SCRATCH, exist_ok=True)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
src = f'{PATCHDIR}/source.s'
binp = f'{SCRATCH}/flatworld.bin'
lstp = f'{SCRATCH}/flatworld.lst'
r = subprocess.run([VASM, '-Fbin', '-L', lstp, '-o', binp, src],
                   capture_output=True, text=True)
print(r.stdout.strip())
if r.returncode != 0:
    print(r.stderr.strip())
    sys.exit(f'vasm failed (rc {r.returncode})')
blob0 = open(binp, 'rb').read()
print(f'blob: {len(blob0)} bytes')

# --- read and verify the original ROM ---
rom = bytearray(open(ORIG, 'rb').read())
assert len(rom) == 0x100000, f'ROM size {len(rom)}'
md5 = hashlib.md5(bytes(rom)).hexdigest()
assert md5 == '30c18fdbe2183f64702ae9f1a45d63f9', f'original MD5 mismatch: {md5}'

blob = open(f'{SCRATCH}/flatworld.bin', 'rb').read()
# padding must be 0xFF from BLOB_BASE to end of ROM
assert all(b == 0xFF for b in rom[BLOB_BASE:]), 'padding at $FD0CC is not 0xFF'
assert BLOB_BASE + len(blob) <= 0x100000, 'blob overflows the ROM'
# the blob must not touch the checksum code region $FD07C-$FD0CB (it starts at $FD0CC)
assert BLOB_BASE >= 0xFD0CC

# --- parse stub addresses from the vasm listing ---
lst = open(f'{SCRATCH}/flatworld.lst', errors='replace').read()
addrs = {}
for m in re.finditer(r'^(\w+)\s+A:([0-9A-Fa-f]{8})\s*$', lst, re.M):
    addrs[m.group(1)] = int(m.group(2), 16)
for name in ('dispatch_hook', 'callsite_stub'):
    assert name in addrs, f'{name} not found in the vasm listing'
    assert addrs[name] >= BLOB_BASE and addrs[name] < BLOB_BASE + len(blob), \
        f'{name} ${addrs[name]:05X} outside the blob'
HOOK = addrs['dispatch_hook']
STUB = addrs['callsite_stub']
print(f'dispatch_hook ${HOOK:05X}, callsite_stub ${STUB:05X} (from flatworld.lst)')

# --- verify the sites to patch (exact ROM bytes, as in the original) ---
def expect(addr, hexbytes, what):
    got = bytes(rom[addr:addr+len(hexbytes)//2]).hex()
    assert got == hexbytes, f'{what} at ${addr:05X}: got {got}, want {hexbytes}'

expect(0xE40C, '2f3620004e75', 'dispatch site A ($E40C: move.l (a6,d2.w),-(a7); rts)')
expect(0xE470, '2f3620004df9000434c04e75', 'dispatch site B ($E470: move.l; lea $434C0,a6; rts)')
expect(0x01BC1A, '4eb90000e358', 'face call site ($01BC1A jsr $E358)')
expect(0x01BC3C, '4eb90000e358', 'hidden call site ($01BC3C jsr $E358)')
expect(0x01BC84, '4eb90000e358', 'top call site ($01BC84 jsr $E358)')

# --- write the blob ---
rom[BLOB_BASE:BLOB_BASE+len(blob)] = blob

# --- patch the dispatch sites (jmp hook.l; B gets 3 nops to fill its 12 bytes) ---
rom[0xE40C:0xE40C+6] = b'\x4e\xf9' + struct.pack('>I', HOOK)
rom[0xE470:0xE470+6] = b'\x4e\xf9' + struct.pack('>I', HOOK)
rom[0xE476:0xE476+6] = b'\x4e\x71\x4e\x71\x4e\x71'

# --- patch the three call sites (jsr callsite_stub.l) ---
for site in (0x01BC1A, 0x01BC3C, 0x01BC84):
    rom[site:site+6] = b'\x4e\xb9' + struct.pack('>I', STUB)

# --- write the ROM, fix both checksums ---
open(OUT, 'wb').write(bytes(rom))
# fix-all takes src and dst (reads src fully before writing dst); use a temp
# dst and rename, so the patched file is never truncated mid-read.
tmp = OUT + '.tmp'
r = subprocess.run([sys.executable, CHECKSUM,
                    'fix-all', OUT, tmp], check=True, capture_output=True, text=True)
print(r.stdout.strip())
os.replace(tmp, OUT)

fixed = open(OUT, 'rb').read()
print(f'fixed ROM MD5: {hashlib.md5(fixed).hexdigest()}')
print(f'header checksum @0x18E: ${struct.unpack(">H", fixed[0x18E:0x190])[0]:04X}')
print(f'runtime immediate @0xFD098: ${struct.unpack(">I", fixed[0xFD098:0xFD09C])[0]:08X}')

# --- verify the patches landed (re-read the fixed ROM) ---
assert fixed[0xE40C:0xE412] == b'\x4e\xf9' + struct.pack('>I', HOOK)
assert fixed[0xE470:0xE476] == b'\x4e\xf9' + struct.pack('>I', HOOK)
assert fixed[0xE476:0xE47C] == b'\x4e\x71\x4e\x71\x4e\x71'
for site in (0x01BC1A, 0x01BC3C, 0x01BC84):
    assert fixed[site:site+6] == b'\x4e\xb9' + struct.pack('>I', STUB)
# blob bytes identical in the fixed ROM
assert fixed[BLOB_BASE:BLOB_BASE+len(blob)] == blob
# original ROM untouched
assert hashlib.md5(open(ORIG, 'rb').read()).hexdigest() == '30c18fdbe2183f64702ae9f1a45d63f9'

# --- changed-bytes.txt ---
orig = open(ORIG, 'rb').read()
diff = [(i, orig[i], fixed[i]) for i in range(len(orig)) if orig[i] != fixed[i]]
os.makedirs(PATCHDIR, exist_ok=True)
with open(f'{PATCHDIR}/changed-bytes.txt', 'w') as f:
    f.write(f'flat-world: {len(diff)} bytes differ from the original ROM\n')
    f.write(f'dispatch_hook ${HOOK:05X}, callsite_stub ${STUB:05X}, blob ${BLOB_BASE:05X}-{BLOB_BASE+len(blob)-1:05X} ({len(blob)} bytes)\n')
    # group contiguous ranges
    ranges = []
    for i, o, n in diff:
        if ranges and ranges[-1][1] == i:
            ranges[-1][1] = i + 1
        else:
            ranges.append([i, i + 1])
    for a, b in ranges:
        f.write(f'  ${a:05X}-${b-1:05X} ({b-a} bytes)\n')
print(f'{len(diff)} bytes differ; ranges written to changed-bytes.txt')

# --- .ips (use the repo tool if present, else a minimal IPS writer) ---
def write_ips(orig_b, fixed_b, path):
    out = bytearray(b'PATCH')
    i = 0
    n = len(orig_b)
    while i < n:
        if orig_b[i] == fixed_b[i]:
            i += 1
            continue
        j = i
        while j < n and orig_b[j] != fixed_b[j] and j - i < 0xFFFF:
            j += 1
        chunk = fixed_b[i:j]
        out += struct.pack('>I', i)[1:] + struct.pack('>H', len(chunk)) + chunk
        i = j
    out += b'EOF'
    open(path, 'wb').write(bytes(out))
    return path
ips = f'{PATCHDIR}/flat-world.ips'
write_ips(orig, fixed, ips)
print(f'wrote {ips} ({os.path.getsize(ips)} bytes)')

# --- IPS round-trip: original + IPS == fixed ROM exactly ---
def apply_ips(orig_b, path):
    d = bytearray(orig_b)
    data = open(path, 'rb').read()
    assert data[:5] == b'PATCH', 'bad IPS header'
    p = 5
    while data[p:p+3] != b'EOF':
        off = int.from_bytes(data[p:p+3], 'big'); p += 3
        ln = int.from_bytes(data[p:p+2], 'big'); p += 2
        if ln == 0:  # RLE
            rlen = int.from_bytes(data[p:p+2], 'big'); p += 2
            val = data[p]; p += 1
            d[off:off+rlen] = bytes([val]) * rlen
        else:
            d[off:off+ln] = data[p:p+ln]; p += ln
    assert data[p:p+3] == b'EOF', 'bad IPS EOF'
    return bytes(d)
assert apply_ips(orig, ips) == fixed, 'IPS round-trip FAILED'
print('IPS round-trip verified: original + IPS == fixed ROM exactly')
print('BUILD OK')
