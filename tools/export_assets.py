#!/usr/bin/env python3
"""Asset export pipeline (issue #19): $DD5C records -> PNG/JSON sources.

The inverse of tools/assets_import.py, and the committed exporter whose
output IS the build input for `make assets` (tools/build_assets.py).
`assets/gfx/` was generated by a one-time scratch exporter that was
never committed; this module is the regenerable replacement — running
it against rop-original.gen reproduces `assets/gfx/` byte-for-byte
(see tools/tests/test_export_assets.py).

Record tables (10-byte entries: u32 offset, u32 decompressed length,
u16 type=1; offsets relative to the data base):

  $96120  62 records, data base 0x09638C (tilesets + tilemaps + text)
  $B86AE  90 records, data base 0x0B8A32 (sprites: [32-B palette][36 tiles])
  $43850 252 records, data base 0x044228 (map chunks: 32x32 or 11x11)

$96120 classification (structural, verified on the ROM):
  * record in tools/decode_map.py KNOWN (21) -> tilemap (rows/cols
    from the $1194A call sites);
  * decompressed length a multiple of 32 -> tileset (37);
  * anything else -> text record, NOT exported (exactly recs 32, 55,
    59, 61 — the #18 text pipeline; they are copied through untouched
    by the build). The exporter asserts the skipped set is exactly
    those four, so a tileset is never silently dropped.

Output format (the authority is tools/assets_import.py + the
committed files; this module reproduces them byte-for-byte):

  manifest.json — {"tables": {...}, "records": [...]} written with
    json.dumps(indent=1), no trailing newline. Records in table order
    96120 (by index), B86AE (0-89), 43850 (0-251).
  tilesets/tileset_recNN.png — $96120 tileset, INDEXED PNG (mode P,
    each pixel IS the palette index 0-15). 16 columns, scale 2, gap 0;
    each tile 16x16 px, grid 256 px wide; tiles = declen / 32. The
    last row may have padding slots, which are index 0 (the image is
    created filled with 0). The PNG palette is the full 256-entry
    (768-byte) PLTE: the 16 display-palette RGB triples, the rest
    zeros — a 48-byte palette would make PIL write bit depth 4 and
    the bytes would differ.
  tilesets/tileset_recNN_pal.json — {"palette_words": [16 CRAM words],
    "palette_index": N}. The words are the master-table palette at
    index N; N is the palette of the first KNOWN map (lowest map
    record) that uses the tileset, else 1 (a map whose palette is
    None counts as 1). Documentary for indexed PNGs (the importer
    ignores the palette in mode P).
  sprites/sprite_recNN.png — $B86AE sprite, INDEXED PNG (mode P).
    6 columns, scale 1, gap 0, 36 tiles — 48x48 px, no padding.
    The PNG palette is the record's embedded palette.
  sprites/sprite_recNN_pal.json — {"palette_words": [16 CRAM words]}
    (big-endian u16 as stored in the record's first 32 bytes).
  maps/map_recNN.json — {"record", "rows", "cols", "entries"} with
    entries {"tile", "flipH", "flipV"} row-major; bits 13-15 are
    never set in $96120 maps, so palette/priority keys are omitted.
  chunks/chunk_recNNN.json — same shape, plus "palette" (0-3) and
    "priority" (bool) per entry when either is set (both keys appear
    together, never independently). 2048 B -> 32x32, 242 B -> 11x11.

CRAM order (corrected #016, live-proven): r=(w>>1)&7, g=(w>>5)&7,
b=(w>>9)&7; each channel scaled x*255//7. The inverse is exact only
for the 8 scaled values (see assets_import.rgb_to_cram_word).

Compression is NOT done here: the exporter writes decompressed
sources. tools/build_assets.py compresses them with tools/dd5c.py
(Okumura encoder, #17) and splices them into the ROM.

Usage:
  python3 tools/export_assets.py [--rom PATH] [--out DIR]
      [--verify REF_DIR]
  --rom:    original ROM (default rop-original.gen in the repo root)
  --out:    output dir (default assets/gfx — CAREFUL: overwrites the
            committed sources; use a scratch dir to compare first)
  --verify: compare the exported dir against a reference dir
            (default: the committed assets/gfx) and report any
            differing / missing / extra file; exit 1 on any mismatch.
Exit 0 when every record is exported (400) and, with --verify, when
the output matches the reference byte-for-byte.
"""
import argparse
import json
import struct
import sys
from pathlib import Path

_here = Path(__file__).resolve().parent
if str(_here) not in sys.path:
    sys.path.insert(0, str(_here))
from dd5c import dd5c_decompress  # noqa: E402  ($DD5C LZSS, #17)
from decode_map import KNOWN  # noqa: E402  (map dims + tileset palettes)
from assets_import import (  # noqa: E402  (CRAM order, palette table)
    cram_word_to_rgb, load_palette_words)

from PIL import Image  # noqa: E402

ROM_DEFAULT = _here.parent / "rop-original.gen"
GFX_DEFAULT = _here.parent / "assets" / "gfx"

# table name -> (table addr, data base, record count)
TABLES = {
    "96120": (0x96120, 0x9638C, 62),
    "B86AE": (0xB86AE, 0xB8A32, 90),
    "43850": (0x43850, 0x44228, 252),
}

# $96120 text records (#18's text pipeline) — the structural rule
# (declen not a multiple of 32) must land exactly on these four.
TEXT_RECORDS = {32, 55, 59, 61}

# $B86AE sprite record layout: [32-byte palette][36 tiles x 32 B].
SPRITE_DECLEN = 1184
SPRITE_TILES = 36

# $43850 chunk sizes: declen -> (rows, cols).
CHUNK_SIZES = {2048: (32, 32), 242: (11, 11)}

# PNG geometry (must match tools/assets_import.py's defaults).
TILESET_COLS, TILESET_SCALE, TILESET_GAP = 16, 2, 0
SPRITE_COLS, SPRITE_SCALE, SPRITE_GAP = 6, 1, 0


def read_records(rom, table, base, n):
    """Decompress every record of a $DD5C table -> list of bytes.

    Asserts type 1 and that the decompressed length matches the table.
    """
    out = []
    for i in range(n):
        off, ln, typ = struct.unpack_from(">IIH", rom, table + i * 10)
        assert typ == 1, "table 0x%X rec %d type %d" % (table, i, typ)
        res = dd5c_decompress(rom, base + off, max_out=200000)
        assert res is not None, "table 0x%X rec %d failed to decompress" % (
            table, i)
        data, _used = res
        assert len(data) == ln, (
            "table 0x%X rec %d: decompressed %d != table %d"
            % (table, i, len(data), ln))
        out.append(data)
    return out


def tileset_palette_index(idx):
    """Master-table palette a tileset is displayed with.

    The palette of the first KNOWN map (lowest map record) that uses
    the tileset, else 1. A map whose palette is None counts as 1.
    """
    for rec in sorted(KNOWN):
        rows, cols, ts, pal, _loader, _note = KNOWN[rec]
        if ts == idx:
            return pal if pal is not None else 1
    return 1


def unpack_tiles(data):
    """Packed tile bytes -> list of 64-index tiles (2 px/byte, hi first)."""
    if len(data) % 32:
        raise ValueError("tile data %d bytes is not a multiple of 32"
                         % len(data))
    tiles = []
    for off in range(0, len(data), 32):
        tile = []
        for b in data[off:off + 32]:
            tile.append(b >> 4)
            tile.append(b & 15)
        tiles.append(tile)
    return tiles


def write_indexed_png(path, tiles, cols, scale, pal_rgb):
    """Tiles -> indexed PNG (mode P, pixels ARE palette indices).

    Geometry: `cols` tiles across, each 8x8 px scaled by `scale`,
    no gap. The image is created filled with index 0, so padding
    slots in the last row are uniform index 0. The palette is the
    full 256-entry (768-byte) PLTE — the 16 RGB triples, the rest
    zeros — which is what makes PIL write bit depth 8 and reproduce
    the committed bytes exactly.
    """
    ntiles = len(tiles)
    rows = (ntiles + cols - 1) // cols
    cell = 8 * scale
    img = Image.new("P", (cols * cell, rows * cell), 0)
    px = img.load()
    for ti, t in enumerate(tiles):
        cx, cy = ti % cols, ti // cols
        for y in range(8):
            for x in range(8):
                v = t[y * 8 + x]
                for sy in range(scale):
                    for sx in range(scale):
                        px[cx * cell + x * scale + sx,
                           cy * cell + y * scale + sy] = v
    flat = []
    for r, g, b in pal_rgb:
        flat += [r, g, b]
    flat += [0] * (768 - len(flat))
    img.putpalette(flat)
    img.save(path)
    return img.size


def write_json(path, obj):
    """json.dumps with default separators, no trailing newline."""
    Path(path).write_text(json.dumps(obj))


def words_to_entries(words, chunk=False):
    """u16 tilemap words -> JSON entries (row-major)."""
    entries = []
    for w in words:
        e = {"tile": w & 0x07FF,
             "flipH": bool(w & 0x0800),
             "flipV": bool(w & 0x1000)}
        if chunk:
            pal = (w >> 13) & 3
            prio = bool(w & 0x8000)
            if pal or prio:
                e["palette"] = pal
                e["priority"] = prio
        entries.append(e)
    return entries


def export_tileset(rom, idx, data, outdir):
    """$96120 tileset -> PNG + palette JSON. Returns the manifest entry."""
    ntiles = len(data) // 32
    pal_idx = tileset_palette_index(idx)
    words = load_palette_words(rom, pal_idx)
    pal_rgb = [cram_word_to_rgb(w) for w in words]
    png = "tilesets/tileset_rec%02d.png" % idx
    write_indexed_png(outdir / png, unpack_tiles(data),
                      TILESET_COLS, TILESET_SCALE, pal_rgb)
    pal_json = "tilesets/tileset_rec%02d_pal.json" % idx
    write_json(outdir / pal_json,
               {"palette_words": list(words), "palette_index": pal_idx})
    return {"table": "96120", "index": idx, "kind": "tileset",
            "src": png, "palette": pal_json,
            "cols": TILESET_COLS, "scale": TILESET_SCALE,
            "gap": TILESET_GAP, "tiles": ntiles}


def export_sprite(idx, data, outdir):
    """$B86AE sprite -> PNG + palette JSON. Returns the manifest entry."""
    assert len(data) == SPRITE_DECLEN, (
        "sprite rec %d: declen %d != %d" % (idx, len(data), SPRITE_DECLEN))
    words = struct.unpack_from(">16H", data, 0)
    pal_rgb = [cram_word_to_rgb(w) for w in words]
    tiles = unpack_tiles(data[32:])
    assert len(tiles) == SPRITE_TILES, (
        "sprite rec %d: %d tiles != %d" % (idx, len(tiles), SPRITE_TILES))
    png = "sprites/sprite_rec%02d.png" % idx
    write_indexed_png(outdir / png, tiles,
                      SPRITE_COLS, SPRITE_SCALE, pal_rgb)
    pal_json = "sprites/sprite_rec%02d_pal.json" % idx
    write_json(outdir / pal_json, {"palette_words": list(words)})
    return {"table": "B86AE", "index": idx, "kind": "sprite",
            "src": png, "palette": pal_json,
            "cols": SPRITE_COLS, "scale": SPRITE_SCALE,
            "gap": SPRITE_GAP, "tiles": SPRITE_TILES}


def export_map(idx, data, outdir):
    """$96120 tilemap -> map JSON. Returns the manifest entry."""
    rows, cols = KNOWN[idx][0], KNOWN[idx][1]
    words = struct.unpack(">%dH" % (len(data) // 2), data)
    assert len(words) == rows * cols, (
        "map rec %d: %d words != %dx%d" % (idx, len(words), rows, cols))
    src = "maps/map_rec%02d.json" % idx
    write_json(outdir / src,
               {"record": idx, "rows": rows, "cols": cols,
                "entries": words_to_entries(words)})
    return {"table": "96120", "index": idx, "kind": "map",
            "src": src, "rows": rows, "cols": cols}


def export_chunk(idx, data, outdir):
    """$43850 chunk -> chunk JSON. Returns the manifest entry."""
    try:
        rows, cols = CHUNK_SIZES[len(data)]
    except KeyError:
        raise ValueError("chunk rec %d: declen %d not 2048 or 242"
                         % (idx, len(data)))
    words = struct.unpack(">%dH" % (len(data) // 2), data)
    assert len(words) == rows * cols, (
        "chunk rec %d: %d words != %dx%d" % (idx, len(words), rows, cols))
    src = "chunks/chunk_rec%03d.json" % idx
    write_json(outdir / src,
               {"record": idx, "rows": rows, "cols": cols,
                "entries": words_to_entries(words, chunk=True)})
    return {"table": "43850", "index": idx, "kind": "chunk",
            "src": src, "rows": rows, "cols": cols}


def export_all(rom_path, out_dir):
    """Export all 400 records from the ROM into out_dir.

    Returns a summary dict: per-kind counts + the skipped text
    records. Writes manifest.json last.
    """
    rom = Path(rom_path).read_bytes()
    outdir = Path(out_dir)
    for sub in ("tilesets", "sprites", "maps", "chunks"):
        (outdir / sub).mkdir(parents=True, exist_ok=True)

    tables = {name: read_records(rom, *spec)
              for name, spec in TABLES.items()}

    records = []
    skipped = []
    for idx, data in enumerate(tables["96120"]):
        if idx in KNOWN:
            records.append(export_map(idx, data, outdir))
        elif len(data) % 32 == 0:
            records.append(export_tileset(rom, idx, data, outdir))
        else:
            skipped.append(idx)  # text record (#18) — not an asset
    if set(skipped) != TEXT_RECORDS:
        raise ValueError("skipped $96120 records %r != expected text "
                         "records %r — a tileset may have been dropped"
                         % (sorted(skipped), sorted(TEXT_RECORDS)))
    for idx, data in enumerate(tables["B86AE"]):
        records.append(export_sprite(idx, data, outdir))
    for idx, data in enumerate(tables["43850"]):
        records.append(export_chunk(idx, data, outdir))

    manifest = {
        "tables": {
            name: {"table_addr": spec[0], "data_base": spec[1],
                   "count": spec[2]}
            for name, spec in TABLES.items()},
        "records": records,
    }
    (outdir / "manifest.json").write_text(json.dumps(manifest, indent=1))

    from collections import Counter
    kinds = Counter(r["kind"] for r in records)
    return {"records": len(records), "kinds": dict(kinds),
            "skipped_text": sorted(skipped)}


def _same_content(a, b):
    """PNGs compare by decoded pixels and mode (the encoder's zlib/metadata
    output varies by Pillow version, so the file bytes do not); everything
    else compares byte-for-byte."""
    if a.suffix.lower() == ".png" and b.suffix.lower() == ".png":
        with Image.open(a) as ia, Image.open(b) as ib:
            return (ia.mode == ib.mode and ia.size == ib.size
                    and ia.tobytes() == ib.tobytes())
    return a.read_bytes() == b.read_bytes()


def compare_dirs(out_dir, ref_dir):
    """Compare an exported dir against a reference (PNG by pixels, rest by bytes).

    Returns (differing, missing, extra): lists of relative paths.
    README.md is excluded: it is hand-written documentation in
    assets/gfx/, not a generated file, so the exporter does not
    reproduce it.
    """
    out_dir, ref_dir = Path(out_dir), Path(ref_dir)
    out_files = {p.relative_to(out_dir) for p in out_dir.rglob("*")
                 if p.is_file()}
    ref_files = {p.relative_to(ref_dir) for p in ref_dir.rglob("*")
                 if p.is_file() and p.name != "README.md"}
    differing = sorted(
        str(p) for p in (out_files & ref_files)
        if not _same_content(out_dir / p, ref_dir / p))
    missing = sorted(str(p) for p in ref_files - out_files)
    extra = sorted(str(p) for p in out_files - ref_files)
    return differing, missing, extra


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--rom", default=str(ROM_DEFAULT))
    ap.add_argument("--out", default=str(GFX_DEFAULT),
                    help="output dir (default: assets/gfx)")
    ap.add_argument("--verify", default=None, metavar="REF_DIR",
                    help="compare the output against a reference dir "
                         "and report any differing/missing/extra file")
    args = ap.parse_args(argv)

    summary = export_all(args.rom, args.out)
    print("exported %d records into %s: %s (skipped text records %s)"
          % (summary["records"], args.out, summary["kinds"],
             summary["skipped_text"]))
    if args.verify is None:
        return 0
    differing, missing, extra = compare_dirs(args.out, args.verify)
    if differing:
        print("differing files (%d):" % len(differing))
        for p in differing:
            print("  " + p)
    if missing:
        print("missing files (%d):" % len(missing))
        for p in missing:
            print("  " + p)
    if extra:
        print("extra files (%d):" % len(extra))
        for p in extra:
            print("  " + p)
    if differing or missing or extra:
        print("VERIFY FAILED: %d differing, %d missing, %d extra"
              % (len(differing), len(missing), len(extra)))
        return 1
    print("verify: output matches %s byte-for-byte (%d files)"
          % (args.verify,
             len([p for p in Path(args.verify).rglob("*") if p.is_file()
                  and p.name != "README.md"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
