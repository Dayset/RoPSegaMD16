#!/usr/bin/env python3
"""First-pass linear disassembly of Rings of Power (Mega Drive) — issue #002.

Uses Capstone (m68k, big-endian). Linear sweep from the reset entry point
0x200 to the end of the ROM. This is pass 1: data regions (text, graphics,
tables) will be mis-decoded as instructions — see disasm/map.md for which
ranges to trust. The script + the original ROM hash are enough to regenerate
the output byte-for-byte.

Usage:
    tools/.venv/bin/python tools/disassemble.py [rom] [out.s]

Defaults: rom=rop-original.gen, out=disasm/rop.s
"""
import hashlib
import struct
import sys

from capstone import Cs, CS_ARCH_M68K, CS_MODE_BIG_ENDIAN

VECTOR_NAMES = [
    "ssp", "reset_pc", "bus_error", "address_error", "illegal_instruction",
    "div_by_zero", "chk", "trapv", "privilege_violation", "trace",
    "line_1010", "line_1111",
] + [f"reserved_{i}" for i in range(12, 24)] + [
    "spurious_interrupt",
    "level1_interrupt", "level2_interrupt", "level3_interrupt",
    "level4_interrupt", "level5_interrupt", "level6_interrupt",
    "level7_interrupt",
] + [f"trap_{i}" for i in range(16)] + [f"reserved_{i}" for i in range(48, 64)]


def main():
    rom_path = sys.argv[1] if len(sys.argv) > 1 else "rop-original.gen"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "disasm/rop.s"
    with open(rom_path, "rb") as f:
        data = f.read()
    md5 = hashlib.md5(data).hexdigest()
    sha1 = hashlib.sha1(data).hexdigest()

    vectors = struct.unpack(">64I", data[0:256])
    targets = {}
    for i, v in enumerate(vectors):
        if v != 0 and 0x200 <= v < len(data):
            targets.setdefault(v, []).append(VECTOR_NAMES[i] if i < len(VECTOR_NAMES) else f"vec_{i}")

    md = Cs(CS_ARCH_M68K, CS_MODE_BIG_ENDIAN)
    md.detail = False
    # Without skipdata Capstone stops at the first undecodable word (e.g. the
    # VDP init data table at 0x28E); with it, undecodable words come back as
    # id==0 pseudo-instructions so the sweep continues through data regions.
    md.skipdata = True

    n_insn = 0
    n_dc = 0
    with open(out_path, "w") as out:
        out.write(f"; Rings of Power (USA, Europe) — first-pass linear disassembly\n")
        out.write(f"; ROM: {rom_path}  size={len(data)}  md5={md5}  sha1={sha1}\n")
        out.write(f"; Generated by tools/disassemble.py (Capstone m68k, linear sweep 0x200..end)\n")
        out.write(f"; WARNING: data regions are mis-decoded as code here — see disasm/map.md\n;\n")
        out.write("; --- Vector table (0x000-0x0FF) ---\n")
        for i, v in enumerate(vectors):
            name = VECTOR_NAMES[i] if i < len(VECTOR_NAMES) else f"vec_{i}"
            out.write(f"; vec {i:3d} {name:24s} = 0x{v:08X}\n")
        out.write(";\n; --- Code from reset entry 0x200 ---\n")

        def flush_dc(start, end):
            # Coalesce a run of undecodable bytes into 16-byte .dc.b lines.
            nonlocal n_dc
            while start < end:
                n = min(16, end - start)
                bs = ", ".join(f"0x{b:02X}" for b in data[start:start + n])
                out.write(f"    .dc.b {bs}    ; 0x{start:06X}-0x{start + n - 1:06X}\n")
                n_dc += n
                start += n

        addr = 0x200
        chunk = 0x10000
        while addr < len(data):
            end = min(addr + chunk, len(data))
            dc_start = None
            for insn in md.disasm(data[addr:end], addr):
                if insn.id == 0:  # skipdata pseudo-instruction: undecodable word
                    if dc_start is None:
                        dc_start = insn.address
                    continue
                if dc_start is not None:
                    flush_dc(dc_start, insn.address)
                    dc_start = None
                if insn.address in targets:
                    out.write(f"\n{'_'.join(targets[insn.address])}:\n")
                hexbytes = " ".join(f"{b:02x}" for b in insn.bytes)
                out.write(f"    {insn.mnemonic:10s} {insn.op_str:28s} ; 0x{insn.address:06X}  {hexbytes}\n")
                n_insn += 1
            if dc_start is not None:
                flush_dc(dc_start, end)
            addr = end
            print(f"  ... 0x{addr:06X}  insn={n_insn} dc={n_dc}", file=sys.stderr)

    print(f"wrote {out_path}: {n_insn} instructions, {n_dc} gap bytes, "
          f"vectors with in-ROM targets: {len(targets)}")


if __name__ == "__main__":
    main()
