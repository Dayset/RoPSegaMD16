#!/usr/bin/env python3
"""gen_src.py — generate disasm/src/rop.s from Ghidra's verified body ranges (issue #012).

Input:  disasm/ghidra/function_bodies.txt  (RANGE entry start end_inclusive)
        rop-original.gen                    (the user's ROM dump)
Output: disasm/src/rop.s

Layout decisions (#012 acceptance):
  * Everything outside a Ghidra body range is data: `incbin` slices of the ROM,
    with start/length recorded in the file. No bytes are typed by hand.
  * Each Ghidra body range is code: one label per function entry, and each
    instruction is emitted as `dc.w` raw words with its Capstone mnemonic in a
    comment. This keeps the rebuild byte-identical by construction; turning the
    words into real mnemonics is the next step, verified per function by the gate.
  * Nothing here is produced by a linear sweep: ranges come from Ghidra's analysis.

Run from the repository root:  python3 tools/gen_src.py
"""
import sys
from pathlib import Path

import capstone

ROM = Path("rop-original.gen")
BODIES = Path("disasm/ghidra/function_bodies.txt")
OUT = Path("disasm/src/rop.s")
ROM_SIZE = 0x100000


def load_ranges():
    """Return sorted (start, end_inclusive, entry) with overlaps merged onto the first entry."""
    rows = []
    for line in BODIES.read_text().splitlines():
        if line.startswith("RANGE "):
            _, entry, start, end = line.split()
            rows.append((int(start, 16), int(end, 16), int(entry, 16)))
    rows.sort()
    merged = []
    for start, end, entry in rows:
        if merged and start <= merged[-1][1]:
            prev = merged[-1]
            merged[-1] = (prev[0], max(prev[1], end), prev[2])
        else:
            merged.append((start, end, entry))
    return merged


def label(addr):
    return f"FUN_{addr:06x}"


def main():
    rom = ROM.read_bytes()
    assert len(rom) == ROM_SIZE, "rop-original.gen must be the 1 MB dump"
    ranges = load_ranges()
    md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_M68K_000)
    md.detail = False

    entries = {}
    for start, end, entry in ranges:
        entries.setdefault(start, set()).add(entry)

    emitted = set()
    out = []
    out.append("; Rings of Power (Mega Drive, USA/Europe) — GENERATED by tools/gen_src.py.")
    out.append("; Do not hand-edit. Code ranges: Ghidra function bodies (disasm/ghidra/function_bodies.txt).")
    out.append("; Data: incbin slices of rop-original.gen. Byte-identity gate: tools/verify_rebuild.py.")
    out.append("\tsection rom,data")
    out.append("\txdef rom_start")
    out.append("rom_start:")

    pos = 0
    code_bytes = 0
    data_slices = 0
    for start, end, entry in ranges:
        if start > pos:
            length = start - pos
            out.append(f"\t; data ${pos:06X}-${start - 1:06X} ({length} bytes)")
            out.append(f'\tincbin "rop-original.gen",${pos:06X},${length:X}')
            data_slices += 1
        # code range
        out.append(f"\t; code ${start:06X}-${end:06X}")
        addr = start
        blob = rom[start:end + 1]
        insns = list(md.disasm(blob, start))
        decoded_end = start
        for insn in insns:
            if insn.address in entries and insn.address not in emitted:
                emitted.add(insn.address)
                out.append(f"{label(insn.address)}:")
            words = rom[insn.address:insn.address + insn.size]
            raw = ",".join(f"${words[i]:02X}{words[i+1]:02X}" for i in range(0, len(words) - len(words) % 2, 2))
            out.append(f"\tdc.w {raw}\t; {insn.mnemonic} {insn.op_str}".rstrip())
            decoded_end = insn.address + insn.size
            code_bytes += insn.size
        # bytes the decoder could not consume within this range
        if decoded_end <= end:
            rest = rom[decoded_end:end + 1]
            out.append(f"\t; undecodable tail ${decoded_end:06X}-${end:06X}")
            raw = ",".join(f"${rest[i]:02X}{rest[i+1]:02X}" for i in range(0, len(rest) - len(rest) % 2, 2))
            if raw:
                out.append(f"\tdc.w {raw}")
            if len(rest) % 2:
                out.append(f"\tdc.b ${rest[-1]:02X}")
            code_bytes += len(rest)
        pos = end + 1

    if pos < ROM_SIZE:
        length = ROM_SIZE - pos
        out.append(f"\t; data ${pos:06X}-${ROM_SIZE - 1:06X} ({length} bytes)")
        out.append(f'\tincbin "rop-original.gen",${pos:06X},${length:X}')
        data_slices += 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(ranges)} code ranges, {data_slices} data slices, {code_bytes} code bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
